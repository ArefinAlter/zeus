//! Explicit media origins, bounded redirects and response-body limits.

use std::collections::BTreeSet;
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::Duration;

use reqwest::header::{LOCATION, USER_AGENT};
use reqwest::{Client, Method, Response, StatusCode};
use url::Url;
use zeus_app::failure::{Failure, Result};

use super::manifest::{MAX_MANIFEST_BYTES, resolve};

/// A private HTTP client bound to the exact origins included in the review.
#[derive(Clone)]
pub struct Network {
    client: Client,
    origins: BTreeSet<String>,
}

impl Network {
    /// Build an anonymous media client. No cookie jar, browser-profile access,
    /// arbitrary request headers or credentials are accepted.
    pub fn new(base: &Url, additional_origins: &[String]) -> Result<Self> {
        if additional_origins.len() > 8 {
            return Err(Failure::invalid(
                "Allow at most eight additional media origins.",
            ));
        }
        let mut origins = BTreeSet::from([base.origin().ascii_serialization()]);
        for origin in additional_origins {
            let url = Url::parse(origin)
                .map_err(|_| Failure::invalid("An allowed media origin is invalid."))?;
            if url.fragment().is_some() {
                return Err(Failure::invalid(
                    "An allowed media origin cannot contain a fragment.",
                ));
            }
            let checked = resolve(&url, "")?;
            if !matches!(checked.path(), "" | "/")
                || checked.query().is_some()
                || checked.fragment().is_some()
            {
                return Err(Failure::invalid(
                    "An allowed media origin contains only its scheme, host and optional port.",
                ));
            }
            origins.insert(checked.origin().ascii_serialization());
        }
        let client = Client::builder()
            .redirect(reqwest::redirect::Policy::none())
            .connect_timeout(Duration::from_secs(15))
            .timeout(Duration::from_secs(90))
            .build()
            .map_err(|_| Failure::new("media.network", "The media HTTP client could not start."))?;
        Ok(Self { client, origins })
    }

    /// The origins shown before selection and saving.
    pub fn origins(&self) -> Vec<String> {
        self.origins.iter().cloned().collect()
    }

    /// Check every resource and redirect before sending a request.
    pub fn check(&self, url: &Url) -> Result<()> {
        resolve(url, "")?;
        if !self.origins.contains(&url.origin().ascii_serialization()) {
            return Err(Failure::new(
                "media.origin_not_allowed",
                format!(
                    "This media uses {}. Add that exact origin to the review and inspect again.",
                    url.origin().ascii_serialization()
                ),
            ));
        }
        Ok(())
    }

    /// Perform a request with bounded, origin-checked redirects. Header values
    /// are generated by the native transfer code, never supplied by a page.
    pub async fn request(
        &self,
        mut url: Url,
        method: Method,
        headers: reqwest::header::HeaderMap,
        cancel: Arc<AtomicBool>,
    ) -> Result<Response> {
        for redirects in 0..=5 {
            self.check(&url)?;
            let request = self
                .client
                .request(method.clone(), url.clone())
                .headers(headers.clone())
                .header(reqwest::header::ACCEPT_ENCODING, "identity")
                .header(USER_AGENT, "Zeus/0.1 media");
            let response = tokio::select! {
                biased;
                _ = cancelled(cancel.clone()) => return Err(canceled()),
                result = request.send() => result.map_err(|_| Failure::new("media.network", "The media host did not complete the request."))?,
            };
            if matches!(
                response.status(),
                StatusCode::MOVED_PERMANENTLY
                    | StatusCode::FOUND
                    | StatusCode::SEE_OTHER
                    | StatusCode::TEMPORARY_REDIRECT
                    | StatusCode::PERMANENT_REDIRECT
            ) {
                if redirects == 5 {
                    return Err(Failure::new(
                        "media.redirect_limit",
                        "The media request exceeds five redirects.",
                    ));
                }
                let location = response
                    .headers()
                    .get(LOCATION)
                    .and_then(|s| s.to_str().ok())
                    .ok_or_else(|| {
                        Failure::new(
                            "media.redirect_invalid",
                            "The media redirect has no valid destination.",
                        )
                    })?;
                let next = resolve(&url, location)?;
                if url.scheme() == "https" && next.scheme() != "https" {
                    return Err(Failure::new(
                        "media.redirect_downgrade",
                        "Zeus refused a media redirect from HTTPS to HTTP.",
                    ));
                }
                url = next;
                continue;
            }
            return Ok(response);
        }
        Err(Failure::new(
            "media.redirect_limit",
            "The media request exceeds five redirects.",
        ))
    }

    /// Fetch one manifest, never more than two MiB. A bounded prefix of an
    /// ordinary media file is not treated as a manifest.
    pub async fn manifest(
        &self,
        url: &Url,
        cancel: Arc<AtomicBool>,
    ) -> Result<(Url, String, String)> {
        let mut response = self
            .request(url.clone(), Method::GET, Default::default(), cancel.clone())
            .await?;
        status(response.status())?;
        identity(response.headers())?;
        if response.status() != StatusCode::OK {
            return Err(Failure::new(
                "media.unexpected_partial",
                "The media host did not return one complete manifest.",
            ));
        }
        let content_type = response
            .headers()
            .get(reqwest::header::CONTENT_TYPE)
            .and_then(|s| s.to_str().ok())
            .unwrap_or("")
            .split(';')
            .next()
            .unwrap_or("")
            .to_ascii_lowercase();
        if response
            .content_length()
            .is_some_and(|n| n > MAX_MANIFEST_BYTES as u64)
        {
            return Err(super::unsupported(
                "The media manifest exceeds two MiB. Use the ordinary download queue for direct media files.",
            ));
        }
        let final_url = response.url().clone();
        let mut bytes = Vec::new();
        loop {
            let part = tokio::select! {
                biased;
                _ = cancelled(cancel.clone()) => return Err(canceled()),
                result = response.chunk() => result.map_err(|_| Failure::new("media.network", "The media manifest ended unexpectedly."))?,
            };
            let Some(part) = part else { break };
            if bytes.len().saturating_add(part.len()) > MAX_MANIFEST_BYTES {
                return Err(super::unsupported("The media manifest exceeds two MiB."));
            }
            bytes.extend_from_slice(&part);
        }
        let text = String::from_utf8(bytes)
            .map_err(|_| super::invalid("Media manifests must use UTF-8 text."))?;
        Ok((final_url, content_type, text))
    }
}

/// Await cooperative cancellation while also allowing in-flight requests to be dropped.
pub async fn cancelled(cancel: Arc<AtomicBool>) {
    while !cancel.load(Ordering::Acquire) {
        tokio::time::sleep(Duration::from_millis(25)).await;
    }
}

/// A redacted cancellation error.
pub fn canceled() -> Failure {
    Failure::new(
        "media.canceled",
        "Media acquisition stopped. Verified segments are kept for an explicit resume.",
    )
}

/// Reject encoded media representations: exact ranges and byte receipts refer
/// to the identity bytes requested by Zeus, never an undeclared gzip stream.
pub(crate) fn identity(headers: &reqwest::header::HeaderMap) -> Result<()> {
    if headers
        .get(reqwest::header::CONTENT_ENCODING)
        .is_some_and(|value| {
            !value
                .to_str()
                .is_ok_and(|value| value.trim().eq_ignore_ascii_case("identity"))
        })
    {
        return Err(Failure::new(
            "media.encoding_unsupported",
            "The media host returned encoded bytes despite the identity-encoding request.",
        ));
    }
    Ok(())
}

/// Classify an HTTP status without exposing addresses or response text.
pub fn status(status: StatusCode) -> Result<()> {
    match status.as_u16() {
        200..=299 => Ok(()),
        401 | 403 => Err(Failure::new(
            "media.auth_or_expired",
            "The media needs authentication or its address expired. No browser credentials were read.",
        )),
        404 | 410 => Err(Failure::new(
            "media.unavailable",
            "The media resource is no longer available.",
        )),
        429 | 503 => Err(Failure::new(
            "media.throttled",
            "The media host is limiting requests. Resume later with fewer connections.",
        )),
        _ => Err(Failure::new(
            "media.http_status",
            format!("The media host returned HTTP {}.", status.as_u16()),
        )),
    }
}
